// Writes docs/sketches.md from the clip registry. Run with `npm run index`.
import { writeFileSync } from 'node:fs';
import { CLIPS } from '../clips/index.js';

const GROUPS = [
    ['time', 'Time clips', 'Drawn from scratch for any frame. Runnable in the player and in Remotion.'],
    ['step', 'Step clips', 'Simulations and paint that build up on the canvas. Runnable.'],
    ['still', 'Stills', 'Too minimal to be a useful clip. Gallery entry only.'],
    ['tool', 'Tools', 'Full tools with their own pages and docs. Not clips.'],
];

const esc = (s) => String(s).replace(/\|/g, '\|');

function links(c) {
    const out = [`\`?artwork=${c.id}\``];
    if (c.runnable) out.push(`\`?clip=${c.id}\``);
    if (c.docs) out.push(`[docs](${c.docs})`);
    return out.join('<br>');
}

const lines = [
    '# Sketch catalogue',
    '',
    '<!-- Generated by scripts/build-index.mjs (npm run index). Do not edit by hand. -->',
    '> Generated, do not edit. Change a `clip.js` and run `npm run index`.',
    '',
    '[← Docs index](README.md) · [Clip library](clips.md)',
];

for (const [kind, title, blurb] of GROUPS) {
    const items = CLIPS.filter((c) => c.kind === kind);
    if (!items.length) continue;
    lines.push('', `## ${title}`, '', blurb, '', '| Name | Id | Description | Modes | Tags | Links |', '|------|----|-------------|-------|------|-------|');
    for (const c of items) {
        const modes = (c.modes ?? []).map((m) => `**${m.id}**: ${m.description}`).join('<br>');
        lines.push(`| ${esc(c.name)} | \`${c.id}\` | ${esc(c.description)} | ${esc(modes)} | ${c.tags.join(', ')} | ${links(c)} |`);
    }
}

writeFileSync(new URL('../docs/sketches.md', import.meta.url), lines.join('\n') + '\n');
console.log(`docs/sketches.md written (${CLIPS.length} entries)`);
